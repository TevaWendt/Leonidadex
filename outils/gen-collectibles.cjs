function sitemapEntry(item) { return '  <url><loc>' + SITE + '/collectibles/' + item.slug + '.html</loc><lastmod>' + item.updatedAt + '</lastmod></url>\n'; }
function sitemap(items) { return '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n' + items.map(sitemapEntry).join('') + '</urlset>\n'; }
function updateSitemap(xml, items, includeHub, hubIndexable) {
  assert(/<urlset\b/.test(xml) && /<\/urlset>/.test(xml), 'sitemap', 'format urlset attendu');
  let result = xml.replace(/[ \t]*<url>[\s\S]*?<\/url>\r?\n?/g, block => {
    const loc = (block.match(/<loc>([^<]+)<\/loc>/) || [])[1] || '';
    return loc.startsWith(SITE + '/collectibles/') || (includeHub && loc === SITE + '/collectibles.html') ? '' : block;
  });
  const entries = (includeHub && hubIndexable ? '  <url><loc>' + SITE + '/collectibles.html</loc></url>\n' : '') + items.map(sitemapEntry).join('');
  return result.replace('</urlset>', entries + '</urlset>');
}
function updateSearchIndex(text, items, data) {
  const match = text.match(/(window\.LK_INDEX\s*=\s*)(\[[\s\S]*\])(\s*;?\s*)$/);
  assert(match, 'search-index.js', 'affectation JSON window.LK_INDEX introuvable');
  const entries = JSON.parse(match[2]);
  assert(Array.isArray(entries), 'search-index.js', 'tableau attendu');
  const preserved = entries.filter(entry => typeof entry.u !== 'string' || !entry.u.startsWith('/collectibles/'));
  if (!preserved.some(entry => entry.u === '/collectibles.html')) preserved.push({ l: 'Collectibles', k: 'Section', u: '/collectibles.html', s: 'collectibles objets a collectionner' });
  const normalize = value => value.normalize('NFD').replace(/[\u0300-\u036f]/g, '').toLowerCase();
  preserved.push(...items.map(item => ({ l: item.name, k: 'Collectible', u: '/collectibles/' + item.slug + '.html', s: normalize([item.name, item.id, categoryName(item, data), item.region, ...item.keywords].filter(Boolean).join(' ')) })));
  return text.slice(0, match.index) + match[1] + json(preserved) + match[3];
}
function updateHub(hub, items, data) {
  const count = items.length, eligible = items.filter(item => item.trackable).length;
  const dateLabel = new Intl.DateTimeFormat('fr-FR', { day: 'numeric', month: 'long', year: 'numeric', timeZone: 'UTC' }).format(new Date(data.updatedAt));
  const inner = (id, content) => { hub = hub.replace(new RegExp('(<([a-z][a-z0-9-]*)\\b[^>]*\\sid="' + id + '"[^>]*>)[\\s\\S]*?(<\\/\\2>)', 'i'), (_, open, tag, close) => open + content + close); };
  const opening = (id, transform) => { hub = hub.replace(new RegExp('<[a-z][a-z0-9-]*\\b[^>]*\\sid="' + id + '"[^>]*>', 'i'), transform); };
  inner('col-documented', String(count));
  inner('col-confirmed', String(items.filter(item => item.status === 'confirmed').length));
  inner('col-located', String(items.filter(item => item.coordinates).length));
  inner('col-help-catalogue-state', count ? 'Le catalogue recense ' + count + ' fiche' + (count > 1 ? 's' : '') + ', dont ' + items.filter(item => item.status === 'confirmed').length + ' confirmée' + (items.filter(item => item.status === 'confirmed').length > 1 ? 's' : '') + ' officiellement. Le total du jeu reste distinct de ce catalogue.' : 'Aucun collectible suffisamment documenté n’est publié pour le moment. Les outils de recherche et de suivi seront utilisables dès les premières fiches vérifiées.');
  inner('col-result-count', count ? count + ' fiche' + (count > 1 ? 's' : '') + ' documentée' + (count > 1 ? 's' : '') : 'Aucune fiche documentée');
  inner('col-status-title', count ? count + ' découverte' + (count > 1 ? 's' : '') + ' documentée' + (count > 1 ? 's' : '') + '.' : 'Des découvertes, quand elles sont documentées.');
  inner('col-status-copy', count ? 'Chaque fiche distingue les informations établies des pistes non confirmées. Revue du catalogue au <time datetime="' + data.updatedAt + '">' + dateLabel + '</time>. Le nombre de fiches décrit notre documentation, pas le total du jeu.' : 'Aucune collection documentée dans les sources vérifiées au <time datetime="' + data.updatedAt + '">' + dateLabel + '</time>. Les noms, emplacements et récompenses seront ajoutés lorsque des preuves suffisantes seront disponibles.');
  inner('col-review-date', dateLabel);
  opening('col-review-date', tag => tag.replace(/datetime="[^"]*"/, 'datetime="' + data.updatedAt + '"'));
  inner('col-review-summary', count ? count + ' fiche' + (count > 1 ? 's' : '') + ' publiée' + (count > 1 ? 's' : '') + ' avec ses sources et son statut de vérification. Les fiches non confirmées restent hors de la progression. Le total des collectibles du jeu reste distinct de ce catalogue.' : 'Aucune collection suffisamment documentée n’a été identifiée au cours de cette revue. Ce constat ne signifie pas que le jeu ne proposera aucun collectible.');
  opening('col-empty', tag => tag.replace(/\shidden(?:="[^"]*")?/g, '').replace(/>$/, count ? ' hidden>' : '>'));
  inner('col-trackable-label', eligible ? 'sur ' + eligible + ' objet' + (eligible > 1 ? 's' : '') + ' suivi' + (eligible > 1 ? 's' : '') : 'objet suivi');
  inner('col-percent', eligible ? '0 %' : '—');
  inner('col-progress-caption', eligible ? 'Le suivi porte sur ' + eligible + ' fiche' + (eligible > 1 ? 's' : '') + ' éligible' + (eligible > 1 ? 's' : '') + ' de ce catalogue. Il ne représente pas le total du jeu.' : 'Le suivi commencera avec les premières fiches éligibles. Le total du jeu est inconnu.');
  opening('col-progress-meter', tag => tag.replace(/aria-valuetext="[^"]*"/, 'aria-valuetext="' + (eligible ? '0 objet trouvé sur ' + eligible + ' fiches éligibles' : 'Progression indisponible : aucun collectible suivi') + '"'));
  return hub;
}
function generate(options = {}) {
  const root = path.resolve(options.root || path.join(__dirname, '..'));
  const sourcePath = path.resolve(options.source || path.join(root, 'outils/collectibles.json'));
  const input = JSON.parse(fs.readFileSync(sourcePath, 'utf8'));
  const data = validateCatalog(input, { root });
  const published = data.items.filter(item => item.published && item.status !== 'placeholder').sort((a, b) => (a.order ?? Number.MAX_SAFE_INTEGER) - (b.order ?? Number.MAX_SAFE_INTEGER) || a.name.localeCompare(b.name, 'fr') || a.id.localeCompare(b.id));
  const indexable = published.filter(isIndexable);
  const publicIds = new Set(published.map(item => item.id));
  const publicData = { ...data, categories: data.categories.filter(category => published.some(item => item.category === category.id)), items: published.map(item => ({ ...item, relatedIds: item.relatedIds.filter(id => publicIds.has(id)) })) };
  const hubPath = path.join(root, 'collectibles.html');
  const hub = fs.readFileSync(hubPath, 'utf8');
  assert(hub.split(START).length === 2 && hub.split(END).length === 2 && hub.indexOf(START) < hub.indexOf(END), 'collectibles.html', 'bornes COLLECTIBLES uniques attendues');
  const parts = templates(hub);
  const outputs = new Map();
  outputs.set('collectibles-data.js', '/* Generated by outils/gen-collectibles.cjs from outils/collectibles.json. */\nwindow.LK_COLLECTIBLES = ' + json(publicData) + ';\n');
  const itemList = published.length ? '<script type="application/ld+json">' + json({ '@context': 'https://schema.org', '@type': 'ItemList', name: 'Collectibles GTA VI documentés sur Leonidakit', numberOfItems: published.length, itemListElement: published.map((item, i) => ({ '@type': 'ListItem', position: i + 1, name: item.name, url: SITE + '/collectibles/' + item.slug + '.html' })) }) + '</script>\n' : '';
  outputs.set('collectibles.html', updateHub(hub.slice(0, hub.indexOf(START) + START.length) + '\n' + itemList + published.map(item => renderCard(item, data)).join('\n') + '\n' + hub.slice(hub.indexOf(END)), published, data));
  for (const item of published) outputs.set('collectibles/' + item.slug + '.html', renderDetail(item, data, parts, published));
  outputs.set('sitemap-collectibles.xml', sitemap(indexable));
  for (const name of ['sitemap.xml', 'sitemap-fiches.xml']) {
    const file = path.join(root, name);
    if (fs.existsSync(file)) outputs.set(name, updateSitemap(fs.readFileSync(file, 'utf8'), indexable, name === 'sitemap.xml', !/<meta\b(?=[^>]*\bname=["']robots["'])(?=[^>]*\bcontent=["'][^"']*\bnoindex\b)[^>]*>/i.test(hub)));
  }
  const searchPath = path.join(root, 'search-index.js');
  if (fs.existsSync(searchPath)) outputs.set('search-index.js', updateSearchIndex(fs.readFileSync(searchPath, 'utf8'), published, data));
  const stale = [];
  const detailDir = path.join(root, 'collectibles');
  if (fs.existsSync(detailDir)) for (const file of fs.readdirSync(detailDir)) {
    if (!file.endsWith('.html') || outputs.has('collectibles/' + file)) continue;
    if (fs.readFileSync(path.join(detailDir, file), 'utf8').includes(MARKER)) stale.push('collectibles/' + file);
  }
  const changed = [...outputs].filter(([name, content]) => !fs.existsSync(path.join(root, name)) || fs.readFileSync(path.join(root, name), 'utf8') !== content).map(([name]) => name);
  for (const name of changed) if (name.startsWith('collectibles/') && fs.existsSync(path.join(root, name))) assert(fs.readFileSync(path.join(root, name), 'utf8').includes(MARKER), name, 'une fiche manuelle occupe ce chemin ; aucun écrasement automatique');
  if (!options.check) {
    for (const name of changed) {
      const target = path.join(root, name);
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, outputs.get(name), 'utf8');
    }
    for (const file of stale) fs.unlinkSync(path.join(root, file));
  }
  return { published: published.length, indexable: indexable.length, changed, removed: stale, valid: true, current: changed.length === 0 && stale.length === 0 };
}
