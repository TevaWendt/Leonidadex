'use strict';
const fs = require('node:fs');
const path = require('node:path');
const SITE = 'https://www.leonidakit.com';
const MARKER = '<!-- Generated by outils/gen-collectibles.cjs; do not edit. -->';
const START = '<!-- COLLECTIBLES:START -->';
const END = '<!-- COLLECTIBLES:END -->';
const STATUSES = { confirmed: 'Confirmé officiellement', established: 'Fortement établi', unconfirmed: 'Non confirmé', placeholder: 'Brouillon' };
const TEXT_FIELDS = ['subcategory', 'summary', 'description', 'region', 'zone', 'place', 'difficulty', 'availability', 'reward'];
const LIST_FIELDS = ['requirements', 'tips', 'hints', 'notes', 'relatedIds', 'keywords'];
const ITEM_KEYS = ['id', 'slug', 'name', 'category', 'status', ...TEXT_FIELDS, 'image', 'gallery', 'coordinates', 'quantity', 'order', ...LIST_FIELDS, 'sources', 'verifiedAt', 'updatedAt', 'seo', 'published', 'trackable'];
const esc = value => String(value == null ? '' : value).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]);
const json = value => JSON.stringify(value).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
const has = (value, key) => Object.prototype.hasOwnProperty.call(value, key);
const assert = (condition, location, message) => { if (!condition) throw new Error(location + ': ' + message); };
function object(value, location, allowed) {
  assert(value !== null && typeof value === 'object' && !Array.isArray(value), location, 'objet attendu');
  if (allowed) for (const key of Object.keys(value)) assert(allowed.includes(key), location + '.' + key, 'champ inconnu');
}
function string(value, location, nullable = false, max = 20000) {
  if (nullable && value == null) return null;
  assert(typeof value === 'string' && value.trim().length > 0 && value.length <= max, location, 'texte non vide attendu (max. ' + max + ')');
  return value.trim();
}
function id(value, location) {
  value = string(value, location, false, 100);
  assert(/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(value) && !['constructor', 'prototype', '__proto__'].includes(value), location, 'identifiant en minuscules, chiffres et tirets attendu');
  return value;
}
function date(value, location, nullable = false) {
  if (nullable && value == null) return null;
  assert(typeof value === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(value) && !Number.isNaN(Date.parse(value)) && new Date(value).toISOString().slice(0, 10) === value, location, 'date ISO réelle YYYY-MM-DD attendue');
  return value;
}
function url(value, location) {
  value = string(value, location, false, 2048);
  let parsed;
  try { parsed = new URL(value); } catch { throw new Error(location + ': URL absolue invalide'); }
  assert(['https:', 'http:'].includes(parsed.protocol) && !parsed.username && !parsed.password, location, 'URL HTTP(S) publique attendue');
  return value;
}
function array(value, location, transform, max = 2000) {
  value = value === undefined ? [] : value;
  assert(Array.isArray(value) && value.length <= max, location, 'tableau attendu (max. ' + max + ')');
  return value.map((entry, i) => transform(entry, location + '[' + i + ']'));
}
function source(value, location) {
  object(value, location, ['label', 'url', 'kind', 'checkedAt']);
  assert(['official', 'community', 'press'].includes(value.kind), location + '.kind', 'official, community ou press attendu');
  return { label: string(value.label, location + '.label', false, 250), url: url(value.url, location + '.url'), kind: value.kind, checkedAt: date(value.checkedAt, location + '.checkedAt') };
}
function image(value, location, root) {
  if (value == null) return null;
  object(value, location, ['src', 'alt', 'width', 'height', 'credit', 'sourceUrl']);
  const src = string(value.src, location + '.src', false, 500);
  assert(/^\/?(?:img|photos)\/[a-zA-Z0-9_./,-]+\.(?:webp|png|jpe?g|avif)$/i.test(src) && !src.split('/').includes('..') && !src.includes('//'), location + '.src', 'image locale sous img/ ou photos/ attendue');
  if (root) assert(fs.existsSync(path.join(root, src.replace(/^\//, ''))) && fs.statSync(path.join(root, src.replace(/^\//, ''))).isFile(), location + '.src', 'image locale introuvable');
  for (const key of ['width', 'height']) assert(Number.isInteger(value[key]) && value[key] > 0 && value[key] <= 20000, location + '.' + key, 'dimension entière de 1 à 20000 attendue');
  return { src: '/' + src.replace(/^\//, ''), alt: string(value.alt, location + '.alt', false, 500), width: value.width, height: value.height, credit: string(value.credit, location + '.credit', false, 500), sourceUrl: url(value.sourceUrl, location + '.sourceUrl') };
}
function coordinates(value, location) {
  if (value == null) return null;
  object(value, location, ['system', 'x', 'y', 'verified', 'sourceUrl']);
  assert(value.system === 'leonidakit-v1' && value.verified === true, location, 'repère leonidakit-v1 et vérification explicite requis');
  for (const [key, max] of [['x', 5200], ['y', 6000]]) assert(Number.isFinite(value[key]) && value[key] >= 0 && value[key] <= max, location + '.' + key, 'coordonnée finie de 0 à ' + max + ' attendue');
  return { system: value.system, x: value.x, y: value.y, verified: true, sourceUrl: url(value.sourceUrl, location + '.sourceUrl') };
}
function validateCatalog(input, options = {}) {
  object(input, 'catalogue', ['schemaVersion', 'updatedAt', 'sources', 'categories', 'items']);
  assert(input.schemaVersion === 1, 'schemaVersion', 'version 1 attendue');
  const data = { schemaVersion: 1, updatedAt: date(input.updatedAt, 'updatedAt'), sources: array(input.sources, 'sources', source), categories: [], items: [] };
  const categories = new Set();
  data.categories = array(input.categories, 'categories', (entry, loc) => {
    object(entry, loc, ['id', 'name', 'description']);
    const category = { id: id(entry.id, loc + '.id'), name: string(entry.name, loc + '.name', false, 200), description: string(entry.description, loc + '.description', true, 2000) };
    assert(!categories.has(category.id), loc + '.id', 'catégorie dupliquée');
    categories.add(category.id);
    return category;
  });
  const ids = new Set(), slugs = new Set();
  assert(Array.isArray(input.items), 'items', 'tableau attendu');
  data.items = array(input.items, 'items', (entry, loc) => {
    object(entry, loc, ITEM_KEYS);
    const item = { id: id(entry.id, loc + '.id'), slug: id(entry.slug, loc + '.slug'), name: string(entry.name, loc + '.name', false, 200), category: entry.category == null ? null : id(entry.category, loc + '.category'), status: entry.status };
    assert(!ids.has(item.id), loc + '.id', 'identifiant dupliqué');
    assert(!slugs.has(item.slug), loc + '.slug', 'slug dupliqué');
    ids.add(item.id); slugs.add(item.slug);
    assert(has(STATUSES, item.status), loc + '.status', 'statut inconnu');
    assert(item.category === null || categories.has(item.category), loc + '.category', 'catégorie non déclarée');
    for (const key of TEXT_FIELDS) item[key] = string(entry[key], loc + '.' + key, true);
    item.image = image(entry.image, loc + '.image', options.root);
    item.gallery = array(entry.gallery, loc + '.gallery', (v, l) => { assert(v != null, l, 'image attendue'); return image(v, l, options.root); }, 30);
    item.coordinates = coordinates(entry.coordinates, loc + '.coordinates');
    for (const key of ['quantity', 'order']) {
      const value = entry[key];
      assert(value == null || (Number.isInteger(value) && value >= (key === 'quantity' ? 1 : 0) && value <= Number.MAX_SAFE_INTEGER), loc + '.' + key, 'entier positif ou null attendu');
      item[key] = value == null ? null : value;
    }
    for (const key of LIST_FIELDS) item[key] = array(entry[key], loc + '.' + key, (v, l) => key === 'relatedIds' ? id(v, l) : string(v, l, false, 2000), 200);
    item.sources = array(entry.sources, loc + '.sources', source, 100);
    item.verifiedAt = date(entry.verifiedAt, loc + '.verifiedAt', true);
    item.updatedAt = date(entry.updatedAt == null ? data.updatedAt : entry.updatedAt, loc + '.updatedAt');
    const seo = entry.seo === undefined ? {} : entry.seo;
    object(seo, loc + '.seo', ['indexable', 'description']);
    assert(seo.indexable === undefined || typeof seo.indexable === 'boolean', loc + '.seo.indexable', 'booléen attendu');
    item.seo = { indexable: seo.indexable === true, description: string(seo.description, loc + '.seo.description', true, 320) };
    for (const key of ['published', 'trackable']) {
      assert(entry[key] === undefined || typeof entry[key] === 'boolean', loc + '.' + key, 'booléen attendu');
      item[key] = entry[key] === true;
    }
    if (item.published && item.status !== 'placeholder') {
      assert(item.sources.length > 0, loc + '.sources', 'une fiche publique exige une source vérifiée');
      assert(item.verifiedAt !== null, loc + '.verifiedAt', 'date de vérification requise pour publier');
      if (item.status === 'confirmed') assert(item.sources.some(s => s.kind === 'official'), loc + '.sources', 'une confirmation officielle exige une source officielle');
    }
    if (item.trackable) assert(['confirmed', 'established'].includes(item.status) && item.published, loc + '.trackable', 'seul un objet publié et établi peut compter dans la progression');
    if (item.coordinates) assert(item.status !== 'placeholder', loc + '.coordinates', 'aucune coordonnée publique pour un brouillon');
    return item;
  }, 20000);
  for (const item of data.items) for (const related of item.relatedIds) assert(ids.has(related) && related !== item.id, item.id + '.relatedIds', 'référence inconnue ou vers soi-même : ' + related);
  return data;
}
function isIndexable(item) {
  const content = [...new Set([item.summary, item.description].filter(Boolean))].join(' ');
  const facts = [item.place, item.coordinates, item.reward, item.requirements.length, item.tips.length, item.quantity !== null, item.availability].filter(Boolean).length;
  return item.published && ['confirmed', 'established'].includes(item.status) && item.seo.indexable && item.sources.length > 0 && item.verifiedAt !== null && ((content.length >= 160 && facts >= 2) || (item.description || '').length >= 600);
}
function categoryName(item, data) { return (data.categories.find(c => c.id === item.category) || {}).name || 'Collectible'; }
function mapLink(item, prefix) { return item.coordinates && item.coordinates.verified === true ? prefix + 'carte.html#collectible=' + encodeURIComponent(item.id) : null; }
function actions(item) {
  return '<div class="col-card-actions" data-col-controls hidden>' + (item.trackable ? '<button type="button" class="col-btn col-btn-primary" data-col-found="' + item.id + '" aria-pressed="false"><span data-col-label>Marquer trouvé</span></button>' : '') + '<button type="button" class="col-btn" data-col-favorite="' + item.id + '" aria-pressed="false"><span data-col-label>Ajouter aux favoris</span></button></div>';
}
function renderCard(item, data, prefix = '') {
  const location = [item.region, item.zone].filter(Boolean).join(' · ');
  return '<article class="col-card" data-col-item="' + item.id + '" data-col-category="' + esc(item.category || '') + '" data-col-status="' + item.status + '">' + (item.image ? '<a class="col-card-media" href="' + prefix + 'collectibles/' + item.slug + '.html" tabindex="-1" aria-hidden="true"><img src="' + esc(item.image.src) + '" width="' + item.image.width + '" height="' + item.image.height + '" alt="" loading="lazy" decoding="async"></a>' : '') + '<div class="col-card-body"><div class="col-tags"><span class="col-tag">' + esc(STATUSES[item.status]) + '</span>' + (item.category ? '<span class="col-tag">' + esc(categoryName(item, data)) + '</span>' : '') + '</div><h3><a href="' + prefix + 'collectibles/' + item.slug + '.html">' + esc(item.name) + '</a></h3>' + (item.summary ? '<p class="col-card-summary">' + esc(item.summary) + '</p>' : '') + (location ? '<p class="col-card-location">' + esc(location) + '</p>' : '') + actions(item) + '</div></article>';
}
function paragraphs(text) { return text ? text.split(/\n\s*\n/).map(p => '<p>' + esc(p).replace(/\n/g, '<br>') + '</p>').join('\n') : ''; }
function list(title, items, spoiler = false, sectionId = null) {
  if (!items.length) return '';
  const body = '<ul>' + items.map(text => '<li>' + esc(text) + '</li>').join('') + '</ul>';
  const identifier = sectionId ? ' id="' + esc(sectionId) + '"' : '';
  return spoiler ? '<details class="col-panel"' + identifier + ' data-col-spoiler><summary>' + esc(title) + '</summary>' + body + '</details>' : '<section class="col-panel"' + identifier + '><h2>' + esc(title) + '</h2>' + body + '</section>';
}
function photo(image, eager = false) {
  return '<figure class="col-detail-image"><a href="' + esc(image.src) + '" aria-label="Agrandir : ' + esc(image.alt) + '" data-col-zoom-alt="' + esc(image.alt) + '" data-col-zoom-credit="' + esc(image.credit) + '"><img src="' + esc(image.src) + '" width="' + image.width + '" height="' + image.height + '" alt="' + esc(image.alt) + '" loading="' + (eager ? 'eager' : 'lazy') + '" decoding="async"></a><figcaption>' + esc(image.credit) + ' · <a href="' + esc(image.sourceUrl) + '" target="_blank" rel="noopener noreferrer">Source du visuel</a></figcaption></figure>';
}
function templates(hub) {
  const header = hub.match(/<a class="skip"[\s\S]*?<\/header>/);
  const footer = hub.match(/<footer>[\s\S]*?<\/footer>/);
  assert(header && footer, 'collectibles.html', 'en-tête/pied de page du site introuvables');
  const relocate = html => html.replace(/\b(href|src)="([^"#][^"]*)"/g, (match, attribute, value) => /^(?:[a-z]+:|\/)/i.test(value) ? match : attribute + '="../' + value + '"');
  return { header: relocate(header[0]), footer: relocate(footer[0]) };
}
